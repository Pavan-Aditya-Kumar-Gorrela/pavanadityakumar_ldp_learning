# &
print(6 & 3)
# 00000110
# &        === 00000010 = 2
# 00000011

# |
print(6 | 3)
# 00000110
# &        === 00000111 = 7
# 00000011

# ~
print(~10)
#  ~00001010 === 11110101 ( -11 )

# ^
print(6 ^ 3)
# 00000110
# ^        === 00000101 = 5
# 00000011

# <<
print(6 << 2)
# 00000110 << 2 == 00011000 ( 24 )

# >>
print(6 >> 2)
# 00000110 >> 2 == 00000001 ( 1 )
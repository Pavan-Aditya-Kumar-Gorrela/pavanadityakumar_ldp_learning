# =
name = "Aditya"
print(name)

# +=
name += " Kumar"
print(name)

# -=
hundred = 100
for i in range(10):
    hundred -= i
print(hundred)

# *=
one = 1
for i in range(1,10):
    one *= i
print(one)

# /=
percent = 90
percent /= 100
print(percent)

# %=
Even = 38
Even %= 2
if Even == 0:
    print("Even")

# //=
temp = 10
temp //= 3
print(temp)

# **=
exp = 3
exp **= exp
print(exp)

# &=
x = 5
x &= 3
print(x)

# |=
x = 5
x |= 3
print(x)

# ^=
x = 5
x ^= 3
print(x)

# >>=
x = 5
x >>= 3
print(x)

# <<=
x = 5
x >>= 3
print(x)

# :=
print(x:=3)